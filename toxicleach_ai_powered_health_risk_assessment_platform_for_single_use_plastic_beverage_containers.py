def predict_health_risk(cup_type, hot_or_cold, cups_per_day, years_used, cup_condition, drink_type):
    metal_df = create_heavy_metal_dataset()

    cup_mapping = {
        "Paper Cup (PE Lined)": "paper_cup_PE_lined",
        "Paper Cup (PLA Lined)": "paper_cup_PLA_lined",
        "Plastic Cup (PP)": "plastic_cup_PP",
        "Plastic Cup (PS)": "plastic_cup_PS",
        "Plastic Cup (PC)": "plastic_cup_PC",
        "Stainless Steel": "stainless_steel",
        "Glass": "glass",
        "Ceramic": "ceramic"
    }

    cup_key = cup_mapping.get(cup_type, "paper_cup_PE_lined")
    cup_data = metal_df[metal_df["cup_type"] == cup_key]

    if len(cup_data) > 0:
        zinc = cup_data["zinc_ppb"].values[0]
        microplastics = cup_data["microplastic_particles_per_liter"].values[0]
    else:
        zinc = microplastics = 0

    # Calculate exposure score
    exposure_score = 0
    exposure_score += 40 if hot_or_cold == "Hot drinks only" else 25 if hot_or_cold == "Both" else 10
    cups_map = {"1-2 cups": 10, "3-5 cups": 25, "6-10 cups": 40, "10+ cups": 55}
    exposure_score += cups_map.get(cups_per_day, 15)
    years_map = {"<1 year": 5, "1-3 years": 15, "3-10 years": 30, "10+ years": 50}
    exposure_score += years_map.get(years_used, 10)
    condition_map = {"New": 0, "Slightly worn": 15, "Scratched": 30, "Old/Cracked": 50}
    exposure_score += condition_map.get(cup_condition, 10)
    exposure_score = min(exposure_score, 100)

    risk_level = "🔴 HIGH RISK" if exposure_score >= 60 else "🟡 MODERATE RISK" if exposure_score >= 30 else "🟢 LOW RISK"

    # Build output
    output = f"""
## 🔬 YOUR PLASTIC CUP HEALTH RISK REPORT

**Cup type:** {cup_type}
**Usage:** {cups_per_day} per day for {years_used}
**Condition:** {cup_condition}
**Drinks:** {hot_or_cold}

---

### 📊 YOUR RISK LEVEL: {risk_level}
**Exposure Score: {exposure_score}/100**

---

### 🩺 HEALTH RISKS IDENTIFIED

"""

    if cup_type in ["Paper Cup (PE Lined)", "Paper Cup (PLA Lined)"]:
        output += "🔴 **Hepatotoxicity (Liver Damage)**: Paper cups leach heavy metals (Zn, Al) and microplastics\n"
        output += "🟡 **Endocrine Disruption**: Phthalates and bisphenols from plastic lining\n"

    if cup_type in ["Plastic Cup (PC)"]:
        output += "🔴 **Reproductive Toxicity**: BPA causes fertility issues and hormonal imbalance\n"

    if cup_type in ["Plastic Cup (PS)"]:
        output += "🔴 **Carcinogenicity**: Styrene oligomers are potential carcinogens\n"

    if microplastics > 1000:
        output += f"🟡 **Toxic Pneumonitis**: {microplastics:,} microplastic particles per liter ingested\n"

    output += """
---

### ✅ SAFER ALTERNATIVES

**Stainless Steel**
- Zero leaching, no plastic lining, BPA-free
- Zinc leaching: 0 ppb | Microplastics: None

**Glass (Borosilicate)**
- Chemically inert, no chemical migration
- Best for hot coffee, tea, water

**Ceramic Mug**
- Glazed surface prevents leaching
- Best for home/office use

---

### 🧪 SCIENCE SUMMARY

• Paper cups contain 5-10% plastic film that degrades with hot liquids
• Hot water (85°C) causes microplastic release within 15 minutes
• Studies detected 5,984 microplastic particles per liter from paper cups
• Heavy metals (Zn 394.54 ppb, Al 58.05 ppb) migrate into beverages

---

### 📚 RESEARCH SOURCES

1. Hossain & Roy (2025). Journal of Hazardous Materials - ML models for plastic chemical toxicity
2. Aktas Sukuroglu et al. (2025). ScienceDirect - Heavy metal migration from paper cups
3. MPLEACH Database (2026). NORMAN Network - Chemical leaching from polymers
"""
    return output

