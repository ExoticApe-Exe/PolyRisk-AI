def create_toxicity_dataset():
    chemical_classes = [
        "Bisphenol A", "Bisphenol S", "Phthalates_DEHP", "Phthalates_DBP",
        "Polystyrene_oligomer", "Polyethylene_additive", "Polypropylene_additive",
        "Antioxidant_Irganox", "UV_stabilizer", "Pigment", "Flame_retardant",
        "Processing_aid", "Monomer_residue", "Degradation_product",
        "Perfluoroalkyl_substance", "Nonylphenol", "Styrene_trimer",
        "Polymer_oligomer", "Plasticizer", "Crosslinking_agent"
    ]

    sources = [
        "plastic_inner_lining", "paper_board_treatment", "adhesive_layer",
        "printing_ink", "recycled_material", "manufacturing_contaminant"
    ]

    beverages = ["hot_water_85C", "hot_coffee", "hot_tea", "cold_water", "cold_soft_drink"]

    np.random.seed(42)
    n_samples = 500

    data = {
        "chemical_name": np.random.choice(chemical_classes, n_samples),
        "source": np.random.choice(sources, n_samples),
        "beverage_type": np.random.choice(beverages, n_samples),
        "contact_time_minutes": np.random.choice([5, 10, 15, 30, 60], n_samples),
        "temperature_celsius": np.random.choice([25, 60, 85, 95], n_samples, p=[0.2, 0.2, 0.4, 0.2]),
        "cup_condition": np.random.choice(["new", "slightly_worn", "scratched", "old"], n_samples),
        "age_days": np.random.randint(1, 365, n_samples),
        "surface_area_cm2": np.random.randint(50, 200, n_samples),
    }

    df = pd.DataFrame(data)

    risk_score = []
    for i in range(n_samples):
        score = 0
        if df.loc[i, "temperature_celsius"] >= 85:
            score += 40
        elif df.loc[i, "temperature_celsius"] >= 60:
            score += 20
        else:
            score += 5

        if df.loc[i, "contact_time_minutes"] >= 30:
            score += 30
        elif df.loc[i, "contact_time_minutes"] >= 15:
            score += 20
        else:
            score += 10

        condition_risk = {"new": 5, "slightly_worn": 15, "scratched": 25, "old": 35}
        score += condition_risk[df.loc[i, "cup_condition"]]

        high_risk_chemicals = ["Bisphenol A", "Phthalates_DEHP", "Phthalates_DBP",
                               "Styrene_trimer", "Perfluoroalkyl_substance"]
        if df.loc[i, "chemical_name"] in high_risk_chemicals:
            score += 25

        if df.loc[i, "source"] == "plastic_inner_lining":
            score += 15

        risk_score.append(min(score, 100))

    df["risk_score"] = risk_score

    endpoints = ["Neurotoxicity", "Hepatotoxicity", "Dermatotoxicity",
                 "Carcinogenicity", "Reproductive_Toxicity"]

    endpoint_results = []
    for i in range(n_samples):
        result = {}
        for endpoint in endpoints:
            if df.loc[i, "risk_score"] > 60:
                result[endpoint] = np.random.choice(["High", "Medium", "Low"], p=[0.6, 0.3, 0.1])
            elif df.loc[i, "risk_score"] > 30:
                result[endpoint] = np.random.choice(["High", "Medium", "Low"], p=[0.2, 0.5, 0.3])
            else:
                result[endpoint] = np.random.choice(["High", "Medium", "Low"], p=[0.05, 0.25, 0.7])

        if df.loc[i, "chemical_name"] in ["Bisphenol A", "Phthalates_DEHP"]:
            result["Reproductive_Toxicity"] = "High"
            result["Neurotoxicity"] = "Medium"
        if df.loc[i, "chemical_name"] in ["Polystyrene_oligomer", "Styrene_trimer"]:
            result["Carcinogenicity"] = "High"

        endpoint_results.append(result)

    endpoint_df = pd.DataFrame(endpoint_results)
    df = pd.concat([df, endpoint_df], axis=1)
    return df

